export function getStopwords(language: SupportedLanguage): Set<string> {
	switch (language) {
		case 'ko':
			return new Set(KO_STOPWORDS);
		case 'en':
			return new Set(EN_STOPWORDS);
		case 'ja':
			return new Set(JA_STOPWORDS);
	}
}

export function getCombinedStopwords(languages: SupportedLanguage[]): Set<string> {
	const combined = new Set<string>();
	for (const lang of languages) {
		for (const word of getStopwords(lang)) {
			combined.add(word);
		}
	}
	return combined;
}
